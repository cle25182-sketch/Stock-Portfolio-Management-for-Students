def _svg(h, body):
    return (f'<svg class="gv" viewBox="0 0 {_W} {h}" xmlns="http://www.w3.org/2000/svg" role="img" '
            f'preserveAspectRatio="xMidYMid meet">{body}</svg>')


def _t(x, y, s, size=13, fill=_NAVY, anchor="start", weight=400, italic=False):
    st = ' font-style="italic"' if italic else ""
    return (f'<text x="{x}" y="{y}" font-size="{size}" fill="{fill}" text-anchor="{anchor}" '
            f'font-weight="{weight}"{st}>{_esc(str(s))}</text>')


def _r(x, y, w, h, fill="none", rx=0, stroke=None, sw=1, dash=None, op=1):
    s = f' stroke="{stroke}" stroke-width="{sw}"' if stroke else ""
    d = f' stroke-dasharray="{dash}"' if dash else ""
    o = f' fill-opacity="{op}"' if op != 1 else ""
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}"{o}{s}{d}/>'


def _l(x1, y1, x2, y2, stroke=_NAVY, sw=1.5, dash=None):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{stroke}" stroke-width="{sw}" stroke-linecap="round"{d}/>'


def _p(points, stroke, sw=2.2, dash=None):
    pts = " ".join(f"{x},{y}" for x, y in points)
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<polyline points="{pts}" fill="none" stroke="{stroke}" stroke-width="{sw}" stroke-linejoin="round" stroke-linecap="round"{d}/>'


def _c(cx, cy, r, fill="none", stroke=None, sw=1.5, dash=None):
    s = f' stroke="{stroke}" stroke-width="{sw}"' if stroke else ""
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{fill}"{s}{d}/>'


def _arrow(x1, y1, x2, y2, color=_NAVY, sw=1.8, head=7):
    a = math.atan2(y2 - y1, x2 - x1)
    hx1, hy1 = x2 - head * math.cos(a - 0.45), y2 - head * math.sin(a - 0.45)
    hx2, hy2 = x2 - head * math.cos(a + 0.45), y2 - head * math.sin(a + 0.45)
    return (_l(x1, y1, x2, y2, color, sw)
            + f'<polygon points="{x2:.1f},{y2:.1f} {hx1:.1f},{hy1:.1f} {hx2:.1f},{hy2:.1f}" fill="{color}"/>')


def _stack(x, y, w, h, fracs, labels=True, min_label=8):
    """แท่งแนวนอนแบ่งตามสัดส่วนเป็น 5 สีแทนหุ้น A–E"""
    out, cx = [], x
    total = sum(fracs)
    for i, f in enumerate(fracs):
        sw = w * f / total
        out.append(_r(round(cx, 1), y, round(sw, 1), h, _PAL[i % 5]))
        if labels and f >= min_label:
            out.append(_t(round(cx + sw / 2, 1), y + h / 2 + 4.5, f"{f}%", 12, "#fff", "middle", 600))
        cx += sw
    return "".join(out)


def _axis_time(y, x1=20, x2=385, left="อดีต", right="ใหม่"):
    return (_arrow(x1, y, x2, y, _INK2, 1.6) + _t(x1, y + 18, left, 12, _INK2) + _t(x2, y + 18, right, 12, _INK2, "end"))


def _bars_row(x, y, tr, te, i_label=None, tr_text="", te_text="", h=24):
    out = [_r(x, y, tr, h, _NAVY), _r(x + tr, y, te, h, _GOLD)]
    if tr_text:
        out.append(_t(x + 8, y + 16, tr_text, 12, "#fff"))
    if te_text:
        out.append(_t(x + tr + te / 2, y + 16, te_text, 12, _NAVY, "middle", 600))
    return "".join(out)


